#!/usr/bin/env node
/**
 * Generate admin/auth secrets and print wrangler + Neon setup steps.
 * Usage: node scripts/configure-admin-env.mjs
 */
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const appDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const devVars = path.join(appDir, '.dev.vars')
const example = path.join(appDir, '.dev.vars.example')

function secret() {
  return randomBytes(32).toString('base64url')
}

const authSecret = secret()
const revalidateSecret = secret()

const lines = [
  '# Generated by scripts/configure-admin-env.mjs — copy to Cloudflare Worker secrets',
  'NEXTJS_ENV=development',
  `AUTH_SECRET=${authSecret}`,
  `BETTER_AUTH_SECRET=${authSecret}`,
  `REVALIDATE_SECRET=${revalidateSecret}`,
  '# Paste your Neon / Supabase connection string:',
  '# DATABASE_URL=postgresql://...',
  'CONTENT_SOURCE=payload',
  'NEXT_PUBLIC_LAUNCH_STATUS=preview',
  'ENABLE_WEB_ADMIN_SCAFFOLD=true',
  '# After first deploy, set to your app origin:',
  '# NEXT_PUBLIC_SITE_URL=https://nagarik-watch-app.workers.dev',
  '# BETTER_AUTH_URL=https://nagarik-watch-app.workers.dev',
  '# First-boot newsroom login (change password after login):',
  'NEWSROOM_SUPERADMIN_EMAIL=owner@nagarikwatch.com',
  `NEWSROOM_SUPERADMIN_PASSWORD=${secret().slice(0, 16)}`,
  'NEWSROOM_SUPERADMIN_NAME=Newsroom Owner',
  'NEWSROOM_ADMIN_EMAIL=editor@nagarikwatch.com',
  `NEWSROOM_ADMIN_PASSWORD=${secret().slice(0, 16)}`,
  'NEWSROOM_ADMIN_NAME=Newsroom Admin',
]

if (!existsSync(devVars)) {
  writeFileSync(devVars, `${lines.join('\n')}\n`, 'utf8')
  console.log(`Wrote ${devVars}`)
} else {
  console.log(`${devVars} already exists — not overwriting.`)
}

writeFileSync(example, `${lines.filter((l) => !l.startsWith('# Generated')).join('\n')}\n`, 'utf8')

console.log(`
Admin configuration checklist
─────────────────────────────
1. Free Postgres: https://neon.tech → create project → copy DATABASE_URL
2. Restore routes (if static build stashed them):
     node scripts/restore-pages-stash.mjs
3. Set Worker secrets (from apps/web):
     pnpm exec wrangler secret put AUTH_SECRET
     pnpm exec wrangler secret put BETTER_AUTH_SECRET
     pnpm exec wrangler secret put REVALIDATE_SECRET
     pnpm exec wrangler secret put DATABASE_URL
4. Deploy full app (admin + API + reader):
     pnpm deploy:app
5. Login: /admin/login with NEWSROOM_SUPERADMIN_* from .dev.vars

Payload CMS (apps/admin) is separate — deploy with Vercel:
     pnpm --filter @nagarikwatch/admin build
Then set CONTENT_SOURCE=payload + PAYLOAD_PUBLIC_SERVER_URL when CMS is live.
`)
